/**
 * Runtime strings for the page controller.
 *
 * The generated HTML carries its own translated text, but the name cards,
 * the chart strip and every toast are built in app.js after a click — long
 * after the page was written to disk. Those strings have to reach the browser
 * somehow, and shipping English ones inside app.js would put English text on
 * /pt/ the moment a visitor pressed the button.
 *
 * So each locale gets one small bundle at /assets/i18n/<code>.js. The home page
 * loads the bundle for its own language and nothing else; app.js reads
 * window.I18N and falls back to the key name only if the bundle is missing.
 *
 * Only the runtime prefixes are included. The page's own copy is already baked
 * into the HTML, so shipping all 295 keys would send the hero and the FAQ down
 * the wire a second time for no reason.
 */
const fs = require('fs');
const path = require('path');
const i18n = require('./_i18n/index.cjs');
const { SHIPPED, getLang, load } = i18n;

const ROOT = path.join(__dirname, 'site');
const OUT = path.join(ROOT, 'assets', 'i18n');

/* Everything app.js can print after a click. `form.` is here because the submit
   button carries its own busy label and the form footer recounts the library. */
const PREFIXES = ['res.', 'card.', 'chart.', 'why.', 'zodiac.', 'cardexport.', 'el.', 'gender.'];
const EXTRA = [
  'form.submit', 'form.submitting', 'form.needinput', 'form.libnote', 'form.privacy',
  'char.crumbgen'
];

function pick(t) {
  const out = {};
  Object.keys(t).forEach(function (k) {
    if (PREFIXES.some(function (p) { return k.indexOf(p) === 0; })) { out[k] = t[k]; return; }
    if (EXTRA.indexOf(k) >= 0) { out[k] = t[k]; }
  });
  return out;
}

/* JSON is valid JS, but a stray </script> inside a string would still close the
   tag if the bundle were ever inlined. Escaping the slash costs nothing. */
function jsString(obj) {
  return JSON.stringify(obj).replace(/<\//g, '<\\/');
}

fs.mkdirSync(OUT, { recursive: true });

let total = 0;
SHIPPED.forEach(function (code) {
  const L = load(code);
  const lang = getLang(code);
  const bundle = {
    code: code,
    lang: lang.htmlLang,
    prefix: lang.prefix,
    ui: pick(L.ui),
    /* The card prints each character's meaning. English reads it from the data
       files it already loaded, but /pt/ and /ko/ need the rewritten gloss. */
    chars: {}
  };
  Object.keys(L.chars || {}).forEach(function (ch) {
    const g = L.chars[ch];
    bundle.chars[ch] = { m: g.m, w: g.w, n: g.n };
  });

  const body = '/* Generated by _gen_i18n_asset.cjs — do not edit. */\n' +
    'window.I18N = ' + jsString(bundle) + ';\n';
  fs.writeFileSync(path.join(OUT, code + '.js'), body, 'utf8');
  total += Object.keys(bundle.ui).length;
  console.log(code.padEnd(3) + ' ' + String(Object.keys(bundle.ui).length).padStart(3) +
    ' keys, ' + Object.keys(bundle.chars).length + ' char glosses, ' +
    (body.length / 1024).toFixed(1) + 'KB');
});

console.log('wrote ' + SHIPPED.length + ' runtime bundles to site/assets/i18n (' + total + ' keys total)');
